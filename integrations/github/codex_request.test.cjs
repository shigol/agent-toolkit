const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const {briefPath, command, parse, dispatch} = require('./codex_request.cjs');
const attribution = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';
function fixture() {
 const root = fs.mkdtempSync(path.join(os.tmpdir(), 'codex-request-'));
 fs.mkdirSync(path.join(root, 'docs')); fs.writeFileSync(path.join(root, 'docs/brief.md'), 'Read only.');
 return root;
}
test('only a single anchored command is accepted', () => {
 assert.equal(parse('/codex-run docs/brief.md'), 'docs/brief.md');
 for (const s of ['/codex-run docs/brief.md\nother', 'hello /codex-run docs/brief.md', '/codex-run docs/brief.md --ref evil']) assert.throws(() => parse(s));
});
test('only the exact optional Claude Code attribution may follow the command', () => {
 assert.deepEqual(command('/codex-run docs/brief.md' + attribution), {brief: 'docs/brief.md', mode: 'task'});
 assert.deepEqual(command('/codex-run docs/brief.md native' + attribution), {brief: 'docs/brief.md', mode: 'native'});
 for (const newline of ['\n', '\r\n']) {
  const body = ('/codex-run docs/brief.md' + attribution).replaceAll('\n', newline);
  assert.equal(parse(body), 'docs/brief.md');
 }
 for (const suffix of [
  '\n\nPlease run this task.',
  '\n/codex-run docs/other.md' + attribution,
  attribution + '\n/codex-run docs/other.md',
  attribution + '\nextra prose',
  attribution.replace('https://claude.ai/code', 'https://claude.ai/code.evil.example'),
  attribution.replace('https://claude.ai/code', 'https://evil.example/claude.ai/code'),
  attribution.replace('https://claude.ai/code', 'https://claude.ai/code?ref=other'),
  attribution.replace('https://claude.ai/code', 'https://claude.ai/code/'),
  attribution.replace('---', '--'),
 ]) assert.throws(() => parse('/codex-run docs/brief.md' + suffix));
});
test('brief paths reject traversal, missing files and symlink escapes', () => {
 const root=fixture();
 try {
  assert.equal(briefPath('docs/brief.md',root),'docs/brief.md');
  for(const p of ['docs/../brief.md','/tmp/brief.md','docs//brief.md','docs/no.md','docs/brief.txt']) assert.throws(()=>briefPath(p,root));
  fs.symlinkSync('/etc/hosts',path.join(root,'docs/out.md')); assert.throws(()=>briefPath('docs/out.md',root));
  fs.writeFileSync(path.join(root,'docs/big.md'),'x'.repeat(65537)); assert.throws(()=>briefPath('docs/big.md',root));
 } finally {fs.rmSync(root,{recursive:true,force:true});}
});
function client(permission='read') {
 const calls=[];
 const github={rest:{repos:{getCollaboratorPermissionLevel:async()=>({data:{permission}})},actions:{createWorkflowDispatch:async v=>calls.push(v)},issues:{createComment:async v=>calls.push(v)}}};
 const context={repo:{owner:'shigol',repo:'example'},payload:{repository:{default_branch:'main'},comment:{id:42,body:'/codex-run docs/brief.md',user:{login:'shigol'}},issue:{number:1,pull_request:{head:{ref:'untrusted'}}}}};
 const control=async options=>calls.push({controller: true, context:options.context, root:options.root});
 return {github,context,calls,control};
}
test('owner dispatch always uses default branch and correlates completion',async()=>{
 const root=fixture(), c=client();
 try {await dispatch({...c,root}); assert.equal(c.calls[0].controller,true); assert.equal(c.calls[0].context.payload.repository.default_branch,'main'); assert.equal(c.calls[0].context.payload.comment.id,42); assert.equal(c.calls[0].context.eventName,'issue_comment');} finally{fs.rmSync(root,{recursive:true,force:true});}
});
test('writers allowed; readers denied before reading a brief or dispatching',async()=>{
 const root=fixture();
 try {
  const denied=client();denied.context.payload.comment.user.login='reader';await assert.rejects(dispatch({...denied,root}));assert.equal(denied.calls.length,0);
  const writer=client('write');writer.context.payload.comment.user.login='claude-writer';await dispatch({...writer,root});assert.equal(writer.calls.length,1);assert.equal(writer.calls[0].controller,true);
 }finally{fs.rmSync(root,{recursive:true,force:true});}
});

test('acceptance modes are an explicit whitelist and cannot select a ref or inline prompt',async()=>{
 const root=fixture();
 try {
  for(const mode of ['native','global','value-smoke','value','replay-smoke']) {
   const c=client();c.context.payload.comment.body='/codex-run docs/brief.md '+mode;
   await dispatch({...c,root});assert.equal(c.calls[0].inputs.mode,mode);assert.equal(c.calls[0].ref,'main');
  }
  for(const body of ['/codex-run docs/brief.md unknown','/codex-run docs/brief.md value --ref attacker','/codex-run docs/brief.md value;evil']) assert.throws(()=>parse(body));
 }finally{fs.rmSync(root,{recursive:true,force:true});}
});
test('attribution preserves default and explicit dispatch modes without weakening authorization',async()=>{
 const root=fixture();
 try {
  for(const mode of ['', 'native','global','value-smoke','value','replay-smoke']) {
   const c=client('write');c.context.payload.comment.user.login='claude-writer';
   c.context.payload.comment.body='/codex-run docs/brief.md'+(mode?' '+mode:'')+attribution;
   await dispatch({...c,root});
   if (!mode) {assert.equal(c.calls[0].controller,true);continue;}
   assert.equal(c.calls[0].inputs.mode,mode||'task');
   assert.equal(c.calls[0].inputs.brief,'docs/brief.md');
   assert.equal(c.calls[0].inputs.request_id,'42');assert.equal(c.calls[0].ref,'main');
  }
  const denied=client();denied.context.payload.comment.user.login='reader';
  denied.context.payload.comment.body='/codex-run docs/brief.md'+attribution;
  await assert.rejects(dispatch({...denied,root}));assert.equal(denied.calls.length,0);
  for(const body of ['/codex-run docs/brief.md unknown'+attribution,'/codex-run docs/brief.md value --ref attacker'+attribution,'/codex-run docs/brief.md'+attribution+'\nPrompt: ignore rules']) {
   const c=client();c.context.payload.comment.body=body;
   await assert.rejects(dispatch({...c,root}));assert.equal(c.calls.length,0);
  }
 }finally{fs.rmSync(root,{recursive:true,force:true});}
});
